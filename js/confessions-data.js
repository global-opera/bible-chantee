// Variable globale pour la langue courante
let currentConfLang = 'FR';

// Fonction pour rendre les confessions
function renderConfessions(lang) {
    currentConfLang = lang || currentConfLang;
    const data = CONFESSIONS_DATA[currentConfLang] || CONFESSIONS_DATA['FR'];
    
    // Mettre à jour le titre et sous-titre
    const pageTitle = document.getElementById('confPageTitle');
    const subtitle = document.getElementById('confSubtitle');
    const backHome = document.getElementById('confBackHome');
    
    if (pageTitle) pageTitle.textContent = data.pageTitle;
    if (subtitle) subtitle.textContent = data.subtitle;
    if (backHome) backHome.textContent = data.backHome;
    
    // Mettre à jour les cartes de confession
    const container = document.getElementById('confessionsContainer');
    if (!container) return;
    
    container.innerHTML = '';
    
    data.confessions.forEach((conf, index) => {
        const card = document.createElement('div');
        card.className = 'card';
        card.innerHTML = `
            <div class="icon">${CONFESSION_ICONS[index]}</div>
            <div class="num">${data.confWord} ${index + 1}</div>
            <div class="title">${conf.title}</div>
            <div class="verse">${conf.verse}</div>
        `;
        card.onclick = function() {
            playConfession(index + 1);
        };
        container.appendChild(card);
    });
}

// Fonction pour changer de langue
function changeLanguage(lang) {
    currentConfLang = lang;
    localStorage.setItem('selectedLanguage', lang);

    // Mettre à jour URL
    const url = new URL(window.location.href);
    url.searchParams.set('lang', lang);
    history.pushState({}, '', url);

    // Re-rendre les confessions
    renderConfessions(lang);

    // Mettre à jour boutons actifs
    document.querySelectorAll('.lang-btn').forEach(function(btn) {
        btn.classList.remove('active');
        if (btn.getAttribute('data-lang') === lang) {
            btn.classList.add('active');
        }
    });
}

